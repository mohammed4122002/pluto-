GEMINI_BASE_URL = "https://generativelanguage.googleapis.com/v1beta/openai/"

# How long to stop attempting OpenAI after it fails in a way that won't fix
# itself on the next message (billing exhausted, bad key). While OPENAI_API_KEY
# was out of credit, every single patient message paid ~3s failing through
# OpenAI — the SDK retries a 429 twice with backoff — before Gemini was even
# asked, which on a plain greeting was most of the wait. Short enough that
# topping the account up recovers on its own without a redeploy.
_OPENAI_COOLDOWN_SECONDS = 600
_openai_unusable_until = 0.0

# Errors that mean "OpenAI will keep failing", as opposed to a transient blip
# worth retrying on the next message.
_OPENAI_HARD_FAILURES = ("insufficient_quota", "credit_balance_exhausted", "invalid_api_key", "account_deactivated")


def _note_openai_failure(exc: Exception) -> None:
    global _openai_unusable_until
    text = str(exc).lower()
    if any(marker in text for marker in _OPENAI_HARD_FAILURES) or "401" in text or "403" in text:
        _openai_unusable_until = time.monotonic() + _OPENAI_COOLDOWN_SECONDS
        logger.warning("OpenAI looks unusable; skipping it for %ss and using the fallback", _OPENAI_COOLDOWN_SECONDS)


def _openai_in_cooldown() -> bool:
    return time.monotonic() < _openai_unusable_until


# Both providers' own error text says these are transient ("usually temporary,
# try again later" / "please retry in Xs") -- unlike _OPENAI_HARD_FAILURES,
# retrying seconds later can genuinely succeed. Distinct from a real quota
# exhaustion (credit_balance_exhausted, or a free-tier "limit: 0") which will
# just fail again immediately.
_RETRYABLE_MARKERS = ("503", "UNAVAILABLE", "429", "RESOURCE_EXHAUSTED")


def _is_retryable_provider_error(exc: Exception) -> bool:
    text = str(exc)
    if any(marker in text for marker in _OPENAI_HARD_FAILURES):
        return False
    return any(marker in text for marker in _RETRYABLE_MARKERS)


def _load_provider_overrides(db: Client) -> dict:
    """Lets clinic staff change the OpenAI/Gemini key from the dashboard
    (backend's /settings/ai-providers) without a redeploy — checked on every
    call so a key change takes effect immediately. Falls back to the
    OPENAI_API_KEY/GEMINI_API_KEY env vars (via the caller) when a column
    here is null, and never lets a lookup hiccup break reply generation."""
    try:
        return db.table("ai_provider_settings").select("*").limit(1).single().execute().data or {}
    except Exception:
        logger.exception("failed to load ai_provider_settings, falling back to env vars")
        return {}


def _decrypt_or_none(value: str | None) -> str | None:
    if not value:
        return None
    try:
        return decrypt_secret(value)
    except Exception:
        logger.exception("failed to decrypt a stored AI provider key, falling back to env var")
        return None


def _get_openai(db: Client = Depends(get_supabase), settings: Settings = Depends(get_settings)) -> OpenAI:
    overrides = _load_provider_overrides(db)
    api_key = _decrypt_or_none(overrides.get("openai_api_key_encrypted")) or settings.openai_api_key
    if not api_key:
        raise HTTPException(
            status_code=501,
            detail="OPENAI_API_KEY not configured — set it in .env or the dashboard's AI settings page.",
        )
    # No in-band retries: a Gemini fallback is already wired up, so retrying a
    # failing OpenAI call here only adds seconds to the patient's wait before
    # we reach for the thing that actually works.
    return OpenAI(api_key=api_key, max_retries=0)


def _get_gemini_fallback(
    db: Client = Depends(get_supabase), settings: Settings = Depends(get_settings)
) -> tuple[OpenAI, str] | None:
    """Gemini exposes an OpenAI-compatible endpoint, so the same OpenAI SDK
    client works against it (just a different base_url/api_key/model) — lets
    _run_conversation_turn fall back without a second code path. Returns None
    when no Gemini key is configured (dashboard or env), in which case an
    OpenAI failure degrades straight to human handoff, same as before this
    fallback existed."""
    overrides = _load_provider_overrides(db)
    api_key = _decrypt_or_none(overrides.get("gemini_api_key_encrypted")) or settings.gemini_api_key
    if not api_key:
        return None
    model = overrides.get("gemini_model") or settings.gemini_model
    return OpenAI(api_key=api_key, base_url=GEMINI_BASE_URL), model


