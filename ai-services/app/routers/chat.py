def _count_ai_turns(db: Client, conversation_id: str, since: str) -> int:
    """Scoped to the current AI episode (since ai_episode_started_at), not the
    conversation's whole lifetime — a conversation stays open indefinitely
    (handle_inbound_message reuses the same row across days), so counting
    forever meant any long-lived thread permanently tripped the cap regardless
    of how the current round was going."""
    result = (
        db.table("messages")
        .select("id", count="exact")
        .eq("conversation_id", conversation_id)
        .eq("sender_type", "ai")
        .gte("created_at", since)
        .execute()
    )
    return result.count or 0


# A patient coming back after this long is starting a new conversation, not
# continuing the old one, so the "this round is going nowhere" turn counter
# starts over for them.
_NEW_SESSION_GAP_MINUTES = 45


def _escalation_keyword_hit(message: str, keywords: list[str]) -> bool:
    """Whether the patient's message trips one of the channel's configured
    escalation keywords.

    Matched on a trailing word boundary rather than as a bare substring: a
    plain `in` test fires on a keyword buried inside an unrelated word, and
    every one of those is a patient pulled out of a working conversation and
    parked in a staff queue for no reason. A leading boundary is deliberately
    *not* required, because Arabic glues its article and conjunctions onto
    the front of a word ("الشكوى", "وشكوى") and those must still match
    "شكوى".

    Single- and two-character keywords are ignored outright: they are almost
    always a misconfiguration, and at that length a coincidental match is
    near-certain in any real sentence."""
    text = (message or "").lower()
    if not text:
        return False
    for keyword in keywords:
        cleaned = (keyword or "").strip().lower()
        if len(cleaned) < 3:
            continue
        if re.search(rf"{re.escape(cleaned)}(?!\w)", text):
            return True
    return False


def _reset_ai_episode(db: Client, conversation_id: str, when: datetime | None = None) -> str:
    """Restarts the AI turn counter, and returns the new episode start.

    max_ai_turns_before_human exists to catch a round that is going nowhere
    and hand it to a human. But the counter only ever restarted on a
    hand-off being reclaimed, never on the AI doing its job -- so once a
    conversation had used up its budget, *every* later message tripped the
    cap forever, and the only way back to a working bot was to be escalated
    and then abandoned for the 20-minute timeout. Confirmed live: a patient
    who wrote nothing but "اهلا" got "someone from our team will contact
    you", as did patients answering "8" and "4"."""
    started_at = (when or datetime.now(timezone.utc)).isoformat()
    try:
        db.table("conversations").update({"ai_episode_started_at": started_at}).eq("id", conversation_id).execute()
    except Exception:
        logger.exception("failed to reset ai episode for conversation %s", conversation_id)
    return started_at


def _previous_message_at(db: Client, conversation_id: str) -> datetime | None:
    """When this conversation was last active, *before* the message being
    answered right now (n8n records the inbound message before calling
    /chat/reply, so the newest row is always the current one)."""
    rows = (
        db.table("messages")
        .select("created_at")
        .eq("conversation_id", conversation_id)
        .order("created_at", desc=True)
        .limit(2)
        .execute()
        .data
    )
    if len(rows) < 2:
        return None
    try:
        return datetime.fromisoformat(rows[1]["created_at"].replace("Z", "+00:00"))
    except (ValueError, KeyError, AttributeError):
        return None


def _episode_start_for_turn(db: Client, conversation_id: str, episode_started_at: str) -> str:
    """The episode start this turn's cap should be measured against, after
    restarting it for a patient who has come back after a long gap."""
    previous = _previous_message_at(db, conversation_id)
    if previous is None:
        return episode_started_at
    if datetime.now(timezone.utc) - previous >= timedelta(minutes=_NEW_SESSION_GAP_MINUTES):
        return _reset_ai_episode(db, conversation_id)
    return episode_started_at


_HISTORY_LIMIT = 24  # ~12 exchanges — see _load_history

_ARABIC_WEEKDAYS = ["الأحد", "الاثنين", "الثلاثاء", "الأربعاء", "الخميس", "الجمعة", "السبت"]


_MEDIA_PLACEHOLDER = {"image": "[صورة]", "audio": "[رسالة صوتية]"}

# Prefix of the note _remember_photo_context leaves on an image message, so a
# re-run recognises its own earlier note instead of stacking another copy.
#
# Worded as an *older* photo on purpose. The note is written after this turn's
# history has already been loaded, so it can only ever be read back on a later
# turn -- by which point the photo it describes really is a previous one. The
# first wording ("صورة أرسلها المريض") didn't say that, and once a patient had
# sent a second photo the model started answering about the wrong one:
# confirmed live, a photo of a hand rash was answered with "the same notes as
# before about your teeth", and a third photo got "this might be a payment
# receipt" -- while the vision model had in fact classified all three
# correctly. The failure was never in the classification, only in which
# analysis the reply reached for.
_PHOTO_CONTEXT_MARKER = "[صورة سابقة بالمحادثة —"


def _load_history(db: Client, conversation_id: str) -> list[dict]:
    """Bounded to the most recent messages, not the conversation's entire
    lifetime — a conversation stays open indefinitely (the same row gets
    reused across days/weeks), so feeding the model unlimited history means
    stale facts from hours or days ago (a doctor who has since been deleted,
    an old failed booking attempt) sit right next to the current question
    with nothing marking them as outdated, and the model has no reliable way
    to tell "still true" from "was true when I said it."

    A photo or voice note with no caption/text has content="" on its own
    row (see 0043_message_media.sql) — left as an empty string here, that
    turn is invisible to the model, which is bad on its own (looks like the
    patient sent nothing) but broke outright on Gemini specifically:
    confirmed live, a genuinely empty trailing user turn gets dropped when
    converted to Gemini's format, so the request actually ends on
    whatever the previous assistant reply was, and Gemini rejects that
    with "Requests ending with a model turn are not supported" — the
    fallback existed for exactly the turns needing it most (OpenAI down)
    and silently failed on every photo/voice message with no caption. A
    short placeholder keeps the turn non-empty for every provider, and the
    patient still lost nothing: what the photo/voice actually showed/said
    is injected separately into the system prompt (see
    _photo_description_for_turn / _transcribe_voice_note_for_turn)."""
    rows = (
        db.table("messages")
        .select("direction, content, media_type")
        .eq("conversation_id", conversation_id)
        .order("created_at", desc=True)
        .limit(_HISTORY_LIMIT)
        .execute()
        .data
    )
    rows.reverse()
    return [
        {
            "role": "user" if r["direction"] == "inbound" else "assistant",
            "content": _strip_photo_note(r["content"]) or _MEDIA_PLACEHOLDER.get(r.get("media_type"), ""),
        }
        for r in rows
    ]


def _strip_photo_note(content: str | None) -> str:
    """Removes the stored analysis of an older photo from a history turn,
    keeping whatever the patient themselves wrote.

    The note is kept on the row (see _remember_photo_context) so a follow-up
    question about a photo still has something to work from, but it must not
    be replayed inside the conversation, where it sits in the model's context
    looking exactly like a fresh analysis. It reliably won that contest:
    confirmed live, a photo of teeth was classified correctly as "أسنان
    ولثة" and the reply still described "احمرار ونتوءات صغيرة على سطح اليد"
    -- the previous photo's note, verbatim, for a completely different body
    part. Wording the note as "previous" and telling the model in the system
    prompt to ignore older notes both failed to stop it; keeping it out of
    the history entirely is what actually does.

    Where it is still needed, it is fetched deliberately and placed in the
    system prompt instead (see _previous_photo_note)."""
    text = content or ""
    marker_at = text.find(_PHOTO_CONTEXT_MARKER)
    if marker_at == -1:
        return text
    return text[:marker_at].strip()


def _latest_inbound_image_url(db: Client, conversation_id: str) -> str | None:
    """The image URL of this conversation's most recent inbound message, if
    it carries one — n8n already downloads a patient's photo and uploads it
    to Supabase Storage before /conversations/inbound ever runs (built for
    payment receipts: db/migrations/0043_message_media.sql), so the URL is
    sitting on the message row by the time this turn starts. Nothing new to
    wire through n8n or the backend for this to work.

    The most recent inbound row is always this turn's message: n8n records
    the inbound message and only then calls /chat/reply, with no interleaving
    possible for a single conversation."""
    rows = (
        db.table("messages")
        .select("media_url, media_type")
        .eq("conversation_id", conversation_id)
        .eq("direction", "inbound")
        .order("created_at", desc=True)
        .limit(1)
        .execute()
        .data
    )
    if not rows or rows[0].get("media_type") != "image":
        return None
    return rows[0].get("media_url") or None


def _latest_inbound_image_message(
    db: Client, conversation_id: str, expected_media_url: str | None = None
) -> dict | None:
    """Like _latest_inbound_image_url, but also carries the message's own id
    — needed so a vision-call failure can be logged to audit_log against
    the right row (see _photo_description_for_turn).

    When expected_media_url is given, resolves that exact row instead of
    whichever image is newest at query time. Without it, two photos sent
    within the ~8-10s a vision call takes race: n8n gives each inbound
    Telegram message its own concurrent execution, so the /chat/reply call
    handling the *first* photo can end up querying "latest inbound image"
    after the *second* photo has already been inserted by the other,
    still-running call -- and answers the wrong one. Confirmed live twice:
    a teeth photo was answered with a hand-rash analysis, and separately a
    second photo in a burst got a generic "you sent several photos" with no
    analysis at all. n8n now passes the media_url straight from the
    Telegram update it received (see ReplyRequest), so each call can look
    up the specific row its own payload is about, independent of how many
    other calls are in flight or how their timing interleaves. Left
    optional because reclaim_stale_conversations has no live payload to
    give one -- it processes one conversation at a time on a schedule, so
    the race this guards against does not apply there."""
    query = (
        db.table("messages")
        .select("id, content, media_url, media_type")
        .eq("conversation_id", conversation_id)
        .eq("direction", "inbound")
    )
    if expected_media_url:
        query = query.eq("media_url", expected_media_url)
    rows = query.order("created_at", desc=True).limit(1).execute().data
    if not rows or rows[0].get("media_type") != "image":
        return None
    return rows[0]


def _remember_photo_context(db: Client, image_row: dict, note: str) -> None:
    """Writes what a photo turned out to be onto the message row itself, so
    later turns still know about it.

    Only the *most recent* inbound message is ever classified, which means a
    patient who sends a photo and then explains it in a second message —
    easily the most natural way to use this — lost the photo entirely on
    that second turn. Confirmed live: a patient sent a photo of an injured
    hand, then wrote "يعاني من هذه الاعراض اللي بالصورة", and that turn ran
    with no photo context at all, so it read as a bare request for a
    diagnosis and got escalated instead of answered.

    Persisting it into content (the same thing _transcribe_voice_note_for_turn
    does with a transcript) means _load_history carries it into every later
    turn, and no second vision call is spent re-deriving it. Any caption the
    patient wrote is kept — it's their own words and must not be overwritten."""
    existing = (image_row.get("content") or "").strip()
    if _PHOTO_CONTEXT_MARKER in existing:
        return
    merged = f"{existing}\n{note}".strip() if existing else note
    try:
        db.table("messages").update({"content": merged}).eq("id", image_row["id"]).execute()
    except Exception:
        # Never fail the turn over this: the patient is waiting on a reply,
        # and this turn already has the analysis in its system prompt.
        logger.exception("failed to persist photo context for message %s", image_row.get("id"))


def _latest_inbound_voice_message(
    db: Client, conversation_id: str, expected_media_url: str | None = None
) -> dict | None:
    """This conversation's most recent inbound message, if it's an
    untranscribed voice note. "Untranscribed" is the key check, not just
    "is a voice note": once transcribe_voice_note_for_turn writes the
    transcript into this same row's content, every later turn (this one
    reprocessed, or a reclaim) must see it as an ordinary text message and
    never spend another Whisper call transcribing it again.

    media_type is "audio", not "voice" — messages.media_type's check
    constraint (0043_message_media.sql) only allows
    image/document/audio/video, and n8n's voice branch sets it to "audio"
    to match. Confirmed live: the first version of this used "voice" and
    every voice note failed outright at the database insert
    (messages_media_type_check violation), before ai-services ever saw it.

    expected_media_url pins this to one exact row instead of "whichever is
    newest right now" -- the same race two quick photos hit (see
    _latest_inbound_image_message), possible here too if a patient sends
    voice notes back to back."""
    query = (
        db.table("messages")
        .select("id, content, media_url, media_type")
        .eq("conversation_id", conversation_id)
        .eq("direction", "inbound")
    )
    if expected_media_url:
        query = query.eq("media_url", expected_media_url)
    rows = query.order("created_at", desc=True).limit(1).execute().data
    if not rows:
        return None
    row = rows[0]
    if row.get("media_type") != "audio" or not row.get("media_url"):
        return None
    if (row.get("content") or "").strip():
        return None
    return row


def _transcribe_voice_note_for_turn(
    db: Client,
    conversation_id: str,
    fallback: tuple[OpenAI, str] | None,
    expected_media_url: str | None = None,
) -> tuple[str | None, bool]:
    """Transcribes this turn's inbound voice note, if there is one still
    waiting on a transcript, and writes the result into the message's own
    content — unlike photo analysis (recomputed fresh every turn, since an
    old photo's relevance fades), a voice note IS what the patient said, and
    every later turn's _load_history must see the exact same text a typed
    message would have produced, not just this one.

    Gemini, not OpenAI/Whisper — same fallback key vision already depends
    on, not a separate credential. Confirmed live: an expired/rotated
    OpenAI key silently broke every voice note with a 401, while text
    replies kept working the whole time because chat completions already
    had a Gemini fallback path and voice transcription (originally
    OpenAI-only, no fallback) didn't. No Gemini configured for this clinic
    means voice notes are skipped the same way photos are — the turn must
    still proceed, never blocked on this.

    Returns (transcript, had_voice_note). had_voice_note is True whenever
    there was a voice note to transcribe at all, whether or not it actually
    worked — generate_reply uses this to tell "no voice note this turn"
    (proceed on payload.message as normal) apart from "there was one and
    transcription failed" (ask the patient to resend/type instead of
    silently answering an empty message). A failure is also recorded to
    audit_log with the real reason (download error, provider error, or an
    empty transcript e.g. from a near-silent/sub-second clip) — the first
    version of this only logged failures to Python's own logger, which
    isn't queryable from here, so a real failure and Gemini genuinely
    hearing nothing looked identical after the fact."""
    voice_row = _latest_inbound_voice_message(db, conversation_id, expected_media_url)
    if not voice_row:
        return None, False
    if not fallback:
        return None, True
    gemini_client, gemini_model = fallback
    text, failure_reason = transcribe_voice_message(gemini_client.api_key, gemini_model, voice_row["media_url"])
    if not text:
        try:
            db.table("audit_log").insert(
                {
                    "entity_type": "voice_transcription",
                    "entity_id": voice_row["id"],
                    "action": "transcription_failed",
                    "reason": failure_reason,
                    "channel": "ai-services",
                }
            ).execute()
        except Exception:
            logger.exception("failed to record voice transcription failure in audit_log")
        return None, True
    db.table("messages").update({"content": text}).eq("id", voice_row["id"]).execute()
    return text, True


def _photo_description_for_turn(
    db: Client,
    conversation_id: str,
    fallback: tuple[OpenAI, str] | None,
    expected_media_url: str | None = None,
) -> tuple[str | None, str | None, bool]:
    """Gemini-only by design: the vision analysis rides on whichever key is
    already configured as the text fallback, rather than needing a second
    key managed separately. No Gemini configured for this clinic simply
    means photos are skipped and the turn proceeds as a normal text-only
    reply — this must never be the reason a patient waiting on a reply
    doesn't get one.

    Returns (description, kind, image_without_medical_description).

    kind is "urgent" or "analysis" (see describe_patient_photo) whenever
    description is set — _build_system_prompt uses it to pick between the
    "push toward urgent care" block and the "structured analysis card"
    block, since those need very different handling and must never be
    conflated. kind is also "receipt" (with no description) when the photo
    is proof of payment, which routes straight to submit_payment_receipt
    instead of either medical block.

    image_without_medical_description is only True when vision actually ran
    and *explicitly* classified the photo as not medical/cosmetic at all —
    a real positive classification, kept strictly separate from a failed
    vision call (see describe_patient_photo's own docstring). Confirmed
    live: a photo of an injured/burned hand got no classification back at
    all (almost certainly a safety filter on a graphic wound image, not
    Gemini actually deciding "not medical"), and this used to treat that
    failure identically to a genuine "none" classification — which routed
    it straight into the receipt-matching path and told the patient their
    payment receipt was received. A failed call now leaves both
    description and image_without_medical_description at their safe
    defaults (nothing shown, no receipt path offered) and is logged to
    audit_log with the real reason, instead of silently picking the wrong
    of two very different outcomes. Also left at defaults whenever there's
    no image, or no way to classify one (no Gemini configured)."""
    image_row = _latest_inbound_image_message(db, conversation_id, expected_media_url)
    if not image_row or not fallback:
        return None, None, False
    vision_client, vision_model = fallback
    kind, text, failure_reason = describe_patient_photo(vision_client.api_key, vision_model, image_row["media_url"])
    if failure_reason:
        try:
            db.table("audit_log").insert(
                {
                    "entity_type": "photo_classification",
                    "entity_id": image_row["id"],
                    "action": "classification_failed",
                    "reason": failure_reason,
                    "channel": "ai-services",
                }
            ).execute()
        except Exception:
            logger.exception("failed to record photo classification failure in audit_log")
        return None, None, False
    if kind is None:
        _remember_photo_context(db, image_row, f"{_PHOTO_CONTEXT_MARKER} ما تبيّن محتواها]")
        return None, None, True
    if kind == "receipt":
        _remember_photo_context(db, image_row, f"{_PHOTO_CONTEXT_MARKER} إثبات دفع]")
        return None, kind, False
    _remember_photo_context(db, image_row, f"{_PHOTO_CONTEXT_MARKER} تحليل مرئي آلي ({kind}): {text}]")
    return text, kind, False


def _patient_said(history: list[dict]) -> str:
    """Only what the patient themselves wrote. The assistant's own replies are
    excluded on purpose: a name it invented in an earlier turn would otherwise
    vouch for itself when validate_full_name checks the name against this."""
    return " ".join(m["content"] or "" for m in history if m["role"] == "user")


